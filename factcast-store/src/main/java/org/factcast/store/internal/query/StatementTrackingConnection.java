package org.factcast.store.internal.query;

import java.sql.*;
import java.util.concurrent.atomic.AtomicBoolean;
import lombok.*;
import lombok.experimental.Delegate;

/**
 * when creating a statement, it'll be registered to the currentStatementHolder and unregisters
 * itself on close.
 */
@RequiredArgsConstructor
class StatementTrackingConnection implements Connection {
  @Delegate final Connection delegate;
  final CurrentStatementHolder currentStatementHolder;

  @Override
  public Statement createStatement() throws SQLException {
    Statement statement = delegate.createStatement();
    currentStatementHolder.register(statement);
    return new ContextStatement(statement);
  }

  @Override
  public Statement createStatement(int resultSetType, int resultSetConcurrency)
      throws SQLException {
    Statement statement = delegate.createStatement(resultSetType, resultSetConcurrency);
    currentStatementHolder.register(statement);
    return new ContextStatement(statement);
  }

  @Override
  public Statement createStatement(
      int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException {
    Statement statement =
        delegate.createStatement(resultSetType, resultSetConcurrency, resultSetHoldability);
    currentStatementHolder.register(statement);
    return new ContextStatement(statement);
  }

  @Override
  public PreparedStatement prepareStatement(String sql) throws SQLException {
    PreparedStatement statement = delegate.prepareStatement(sql);
    currentStatementHolder.register(statement);
    return new ContextPreparedStatement(statement);
  }

  @Override
  public PreparedStatement prepareStatement(String sql, int[] columnIndexes) throws SQLException {
    PreparedStatement statement = delegate.prepareStatement(sql, columnIndexes);
    currentStatementHolder.register(statement);
    return new ContextPreparedStatement(statement);
  }

  @Override
  public PreparedStatement prepareStatement(String sql, String[] columnNames) throws SQLException {
    PreparedStatement statement = delegate.prepareStatement(sql, columnNames);
    currentStatementHolder.register(statement);
    return new ContextPreparedStatement(statement);
  }

  @Override
  public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException {
    PreparedStatement statement = delegate.prepareStatement(sql, autoGeneratedKeys);
    currentStatementHolder.register(statement);
    return new ContextPreparedStatement(statement);
  }

  @Override
  public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency)
      throws SQLException {
    PreparedStatement statement =
        delegate.prepareStatement(sql, resultSetType, resultSetConcurrency);
    currentStatementHolder.register(statement);
    return new ContextPreparedStatement(statement);
  }

  @Override
  public PreparedStatement prepareStatement(
      String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability)
      throws SQLException {
    PreparedStatement statement =
        delegate.prepareStatement(sql, resultSetType, resultSetConcurrency, resultSetHoldability);
    currentStatementHolder.register(statement);
    return new ContextPreparedStatement(statement);
  }

  @Override
  public CallableStatement prepareCall(String sql) throws SQLException {
    CallableStatement statement = delegate.prepareCall(sql);
    currentStatementHolder.register(statement);
    return new ContextCallableStatement(statement);
  }

  @Override
  public CallableStatement prepareCall(String sql, int resultSetType, int resultSetConcurrency)
      throws SQLException {
    CallableStatement statement = delegate.prepareCall(sql, resultSetType, resultSetConcurrency);
    currentStatementHolder.register(statement);
    return new ContextCallableStatement(statement);
  }

  @Override
  public CallableStatement prepareCall(
      String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability)
      throws SQLException {
    CallableStatement statement =
        delegate.prepareCall(sql, resultSetType, resultSetConcurrency, resultSetHoldability);
    currentStatementHolder.register(statement);
    return new ContextCallableStatement(statement);
  }

  abstract class AbstractContextStatement implements Statement {
    // unfortunately, tomcat jdbc relies of calling close more than once, so that we'll have to
    // guard here
    final AtomicBoolean closed = new AtomicBoolean(false);

    void closeAndClear(Statement s) throws SQLException {
      if (!closed.getAndSet(true))
        try {
          s.close();
        } finally {
          currentStatementHolder.unregister(s);
        }
    }

    void closeOnCompletionAndClear(Statement s) throws SQLException {
      if (!closed.getAndSet(true))
        try {
          s.closeOnCompletion();
        } finally {
          currentStatementHolder.unregister(s);
        }
    }
  }

  @RequiredArgsConstructor
  class ContextStatement extends AbstractContextStatement {
    @Getter(AccessLevel.PROTECTED)
    @Delegate
    final Statement delegate;

    @Override
    public final void close() throws SQLException {
      closeAndClear(delegate);
    }

    @Override
    public final void closeOnCompletion() throws SQLException {
      closeOnCompletionAndClear(delegate);
    }
  }

  @RequiredArgsConstructor
  class ContextPreparedStatement extends AbstractContextStatement implements PreparedStatement {
    @Getter(AccessLevel.PROTECTED)
    @Delegate
    final PreparedStatement delegate;

    @Override
    public final void close() throws SQLException {
      closeAndClear(delegate);
    }

    @Override
    public final void closeOnCompletion() throws SQLException {
      closeOnCompletionAndClear(delegate);
    }
  }

  @RequiredArgsConstructor
  class ContextCallableStatement extends AbstractContextStatement implements CallableStatement {
    @Getter(AccessLevel.PROTECTED)
    @Delegate
    final CallableStatement delegate;

    @Override
    public final void close() throws SQLException {
      closeAndClear(delegate);
    }

    @Override
    public final void closeOnCompletion() throws SQLException {
      closeOnCompletionAndClear(delegate);
    }
  }
}
